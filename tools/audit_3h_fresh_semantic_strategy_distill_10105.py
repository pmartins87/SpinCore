"""Fresh semantic-strategy distillation bridge for frozen 10105 3H.

Why this exists:
The historical strategy reservoir was generated by the historical V1 Advantage
sequence. The previous AveragePolicy semantic continuation therefore asked a
semantic model to fit stale V1 strategy targets and correctly failed to show a
semantic benefit.

This gate instead:
1) freezes the already-passed eight-member 1600-step V1+semantic Advantage
   shadow;
2) generates fresh 3H sampled trajectories under its raw-Advantage ensemble;
3) records the resulting contemporaneous sigma as fresh strategy targets;
4) splits by whole episodes into train/holdout;
5) adapts two AveragePolicy arms from the exact finalized 10105 policy:
      A) V1 control
      B) V1 + the same 30 general semantic features
   with exact shared minibatches and copied Adam history;
6) compares holdout strategy CE/TV and the high-card/no-draw ALL_IN subgroup.

No CFR Advantage targets are generated, no checkpoint is mutated, and nothing
is promoted to production.
"""

